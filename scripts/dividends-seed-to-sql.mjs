// Regenerates the seed block of the migration from src/data/seed.json,
// so the sample data the page falls back to and the database never drift.
import { readFileSync, writeFileSync } from 'node:fs';
const seed = JSON.parse(readFileSync(new URL('../src/data/seed.json', import.meta.url)));
const q = (v) => (v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const cols = ['symbol','fiscal_year','kind','amount','currency','announced_on','ex_date','record_date','pay_date','agm_date','verified','source_url','notes'];
const rows = seed.map((d) => `  (${cols.map((c) => q(d[c])).join(', ')})`).join(',\n');
const sql = `insert into public.dividend (${cols.join(', ')}) values
${rows}
on conflict (symbol, fiscal_year, kind) do update set
  amount = excluded.amount, currency = excluded.currency, announced_on = excluded.announced_on,
  ex_date = excluded.ex_date, record_date = excluded.record_date, pay_date = excluded.pay_date,
  agm_date = excluded.agm_date, verified = excluded.verified, source_url = excluded.source_url,
  notes = excluded.notes;
`;
const path = new URL('../supabase/migrations/0009_dividend_calendar.sql', import.meta.url);
const mig = readFileSync(path, 'utf8');
const start = '-- >>> seed (generated by scripts/seed-to-sql.js)';
const end = '-- <<< seed';
const a = mig.indexOf(start), b = mig.indexOf(end);
if (a < 0 || b < 0) throw new Error('seed markers missing');
const out = mig.slice(0, a) + `${start}\n${sql}` + mig.slice(b);
writeFileSync(path, out);
console.log(`seeded ${seed.length} rows into 0009_dividend_calendar.sql`);
