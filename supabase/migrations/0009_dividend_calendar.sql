-- 0009 · Dividend calendar
-- One row per declared dividend, with every date an investor cares about.
-- Additive only: nothing existing is altered. To undo:
--   drop view public.dividend_calendar; drop table public.dividend;

create table if not exists public.dividend (
  id            bigint generated always as identity primary key,
  symbol        varchar not null references public.instrument(symbol),
  fiscal_year   text    not null,                       -- e.g. 'FY2025', 'FY2026 (Mar)', 'FY2026 H1'
  kind          text    not null check (kind in ('final', 'interim', 'special')),
  amount        numeric(14,4) not null check (amount > 0), -- gross per share, as declared (pre any later split)
  currency      varchar(3) not null default 'TZS',
  announced_on  date,
  ex_date       date,      -- first day shares trade without the dividend
  record_date   date,      -- closure of members' register (books closure)
  pay_date      date,
  agm_date      date,
  verified      boolean not null default false,  -- true once checked against the company / DSE notice
  source_url    text,
  notes         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (symbol, fiscal_year, kind),
  constraint dividend_ex_before_record check (ex_date is null or record_date is null or ex_date <= record_date),
  constraint dividend_pay_after_record check (pay_date is null or record_date is null or pay_date >= record_date)
);

create index if not exists dividend_pay_date_idx on public.dividend (pay_date);
create index if not exists dividend_symbol_idx   on public.dividend (symbol);

create or replace function public.dividend_touch() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;

drop trigger if exists dividend_touch on public.dividend;
create trigger dividend_touch before update on public.dividend
  for each row execute function public.dividend_touch();

alter table public.dividend enable row level security;
drop policy if exists "public read dividends" on public.dividend;
create policy "public read dividends" on public.dividend for select to anon, authenticated using (true);
-- No insert/update policy: rows are maintained from the dashboard or with the service key.

-- What the page and the .ics feed read: dividends with company name and latest close.
create or replace view public.dividend_calendar with (security_invoker = true) as
select d.id, d.symbol, i.name, d.fiscal_year, d.kind, d.amount, d.currency,
       d.announced_on, d.ex_date, d.record_date, d.pay_date, d.agm_date,
       d.verified, d.source_url, d.notes, d.updated_at,
       p.close as price, p.trade_date as price_date
from public.dividend d
join public.instrument i on i.symbol = d.symbol
left join lateral (
  select pd.close, pd.trade_date
  from public.price_daily pd
  where pd.symbol = d.symbol and pd.close > 0
  order by pd.trade_date desc
  limit 1
) p on true;

grant select on public.dividend_calendar to anon, authenticated;

